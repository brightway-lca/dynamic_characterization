    ref = (co2, ch4, n2o)
    re_co2_ppm = meinshausen((co2 + 1, ch4, n2o), ref)[0] * (1 + 0.05)
    re_ch4_direct = meinshausen((co2, ch4 + 1, n2o), ref)[1] * (1 - 0.14)
    re_n2o_direct = meinshausen((co2, ch4, n2o + 1), ref)[2] * (1 + 0.07)

