# --- indirect (precursor) gases -----------------------------------------------------------

# Time constant for components that the sources treat as acting within the first year (short-
# lived O3, sulfate, nitrate): the tropospheric O3 response time of Fuglestvedt et al. (2010),
# Section 7.3. At annual resolution it only moves forcing within the first year after emission.
SHORT_LIVED = 0.267
SHORT_LIVED_SOURCE = "short-lived: tau_O3 = 0.267 yr, Fuglestvedt et al. 2010 Section 7.3"

# AGWP of CO2 [W m-2 yr kg-1] that the sources used for their published GWPs (test references)
AGWP_CO2_FRY2012 = {"20": 2.42e-14, "100": 8.56e-14}  # implied by Fry et al. 2012 Table S2
AGWP_CO2_AR4 = {"20": 2.47e-14, "100": 8.69e-14, "500": 28.6e-14}  # AR4 WG1 Table 2.14


def _component(name, forcing, response_time, source, response_time_source=None, status="literature"):
    return {
        "name": name,
        "steady_state_forcing": forcing,
        "response_time": response_time,
        "source": source,
        "response_time_source": response_time_source or source,
        "status": status,
    }


def _fry2012(species, basis, o3_short, o3_long, ch4, so4, published):
    table = f"Fry et al. 2012, '4 regions' {species}: Table S1 net RF / Table 3 emission change; O3 short/long split from the Table S2 O3/CH4 GWP ratios"
    return {
        "basis": basis,
        "precursor_lifetime": 0.0,
        "precursor_lifetime_source": "neglected (Fry et al. 2012)",
        "status": "literature",
        "components": [
            _component("O3, short-term", o3_short, SHORT_LIVED, table, SHORT_LIVED_SOURCE, "fallback"),
            _component("O3, long-term (CH4-induced)", o3_long, 11.65, table, "multi-model CH4 perturbation lifetime, Fry et al. 2012 para. 35-36"),
            _component("CH4", ch4, 11.65, table, "multi-model CH4 perturbation lifetime, Fry et al. 2012 para. 35-36"),
            _component("sulfate", so4, SHORT_LIVED, table, SHORT_LIVED_SOURCE, "fallback"),
        ],
        "published": dict(published, source="Fry et al. 2012, Table S2 ('4 regions')", agwp_co2=AGWP_CO2_FRY2012),
    }


def _fuglestvedt2010(source_study, basis, components, lifetime, published, row):
    table = f"Fuglestvedt et al. 2010, Table 3, {row} ({source_study})"
    comps = [
        _component(name, forcing, SHORT_LIVED if short else lifetime, table, SHORT_LIVED_SOURCE if short else table)
        for name, forcing, short in components
    ]
    return {
        "basis": basis,
        "precursor_lifetime": 0.0,
        "precursor_lifetime_source": "neglected (Fuglestvedt et al. 2010)",
        "status": "literature",
        "components": comps,
        "published": {"total": published, "horizons": [20, 100, 500], "agwp_co2": AGWP_CO2_AR4, "source": "Fuglestvedt et al. 2010, Table 4a"},
    }


def _warwick2023():
    """H2, Warwick et al. 2023 (Eq. 5, Supplement Table S1), UKESM1 with AR6 radiative efficiencies."""
    alpha_h2 = 1.96  # yr, H2 lifetime (range 1.4-2.2)
    c = 3.5e-9  # ppb kg-1 (Supplement Table S1; 3.52e-9 in the main text)
    a_ch4, alpha_ch4, r_ch4 = 0.0146, 11.8, 3.892e-4
    a_o3, alpha_o3, r_o3 = 5.62e-3, 0.07, 0.042
    a_h2o, alpha_h2o, r_h2o = 0.041, 8.0, 1e-4
    f_ch4 = r_ch4 * a_ch4 * alpha_h2 * alpha_ch4 * c
    src = "Warwick et al. 2023, Eq. 5 and Supplement Table S1: F_ss = R a alpha_H2 alpha_M C"
    return {
        "basis": "kg H2",
        "precursor_lifetime": alpha_h2,
        "precursor_lifetime_source": "Warwick et al. 2023 (range 1.4-2.2 yr)",
        "status": "literature",
        "components": [
            _component("CH4", f_ch4, alpha_ch4, src),
            _component("O3, CH4-induced", 0.37 * f_ch4, alpha_ch4, src + "; 0.37 x CH4 (AR6 scaling)"),
            _component("stratospheric H2O, CH4-induced", 0.106 * f_ch4, alpha_ch4, src + "; 0.106 x CH4 (AR6 scaling)"),
            _component("O3, tropospheric", r_o3 * a_o3 * alpha_h2 * alpha_o3 * c, alpha_o3, src),
            _component("stratospheric H2O", r_h2o * a_h2o * alpha_h2 * alpha_h2o * c, alpha_h2o, src),
        ],
        "published": {
            "total": [34.4, 11.5],
            "horizons": [20, 100],
            "components": {"CH4": [14.7, 5.2], "O3": [10.0, 3.2], "stratospheric H2O": [9.7, 3.1]},
            "agwp_co2": "ar6",
            "source": "Warwick et al. 2023, Table 3 (AR6 column)",
        },
    }


def _sand2023():
    """H2, Sand et al. 2023 (Supplementary Tables 1, 3, 4, 8), multi-model means."""
    per_tg = 1e-3 / 1e9  # mW m-2 per (Tg yr-1) -> W m-2 per (kg yr-1)
    src = "Sand et al. 2023, Supplementary Tables 1, 3, 4 (steady-state ERF per H2 flux, multi-model mean)"
    instantaneous = "not given by Sand et al.; instantaneous (follows the H2 lifetime), as Sand et al. assume"
    return {
        "basis": "kg H2",
        "precursor_lifetime": 2.4,
        "precursor_lifetime_source": "Sand et al. 2023, H2 total lifetime",
        "status": "literature",
        "components": [
            _component("CH4", 0.46 * per_tg, 11.8, src, "CH4 decay time, Sand et al. 2023 Supplementary Table 8"),
            _component("O3, CH4-induced", (0.40 - 0.18) * per_tg, 11.8, src + "; total O3 0.40 minus direct 0.18", "CH4 decay time, Sand et al. 2023 Supplementary Table 8"),
            _component("stratospheric H2O, CH4-induced", (0.19 - 0.13) * per_tg, 11.8, src + "; total 0.19 minus direct 0.13", "CH4 decay time, Sand et al. 2023 Supplementary Table 8"),
            _component("O3, tropospheric", 0.18 * per_tg, 0.0, src, instantaneous, "fallback"),
            _component("stratospheric H2O", 0.13 * per_tg, 0.0, src, instantaneous, "fallback"),
        ],
        "published": {"total": [37.3, 11.6, 3.31], "horizons": [20, 100, 500], "agwp_co2": "ar6", "source": "Sand et al. 2023, main text"},
    }


