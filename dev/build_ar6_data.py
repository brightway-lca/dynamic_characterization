"""Generate ``dynamic_characterization/ipcc_ar6/data/ar6_parameters.json``.

Every value follows the IPCC AR6 metric code (https://github.com/chrisroadmap/ar6, commit
24f279260fc2d1ebd09b2bd4114f2be11859e925, ``src/ar6/metrics`` and notebook
``335_chapter7_generate_metrics.ipynb``), which produced AR6 WG1 Table 7.SM.7. The radiative
efficiencies of CO2, CH4 and N2O are the Meinshausen et al. (2020) forcing for a +1 ppm / +1 ppb
perturbation at the notebook's 2019 background concentrations, times the AR6 tropospheric
adjustments, exactly as in that code. The formula is reimplemented here (identical to
``fair.forcing.ghg.meinshausen``), so the package needs no FaIR dependency.

    python dev/build_ar6_data.py           # write the file
    python dev/build_ar6_data.py --check   # exit 1 if the file is out of date
"""

import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "dynamic_characterization", "ipcc_ar6", "data", "ar6_parameters.json")

AR6_CODE = "https://github.com/chrisroadmap/ar6 (commit 24f279260fc2d1ebd09b2bd4114f2be11859e925)"

# Meinshausen et al. (2020), Table 3 (as in fair.forcing.ghg.meinshausen)
A1, B1, C1, D1 = -2.4785e-07, 0.00075906, -0.0021492, 5.2488
A2, B2, C2, D2 = -0.00034197, 0.00025455, -0.00024357, 0.12173
A3, B3, D3 = -8.9603e-05, -0.00012462, 0.045194

# background concentrations of notebook 335 (cell 7): CO2 ppm, CH4 ppb, N2O ppb
BACKGROUND = {"co2": 409.9, "ch4": 1866.3, "n2o": 332.1}


def meinshausen(conc, ref):
    """ERF of (co2, ch4, n2o) relative to ``ref`` (fair.forcing.ghg.meinshausen, scale_F2x=False)."""
    co2, ch4, n2o = conc
    co2_ref, ch4_ref, n2o_ref = ref
    ca_max = co2_ref - B1 / (2 * A1)
    if co2_ref < co2 <= ca_max:
        alpha_p = D1 + A1 * (co2 - co2_ref) ** 2 + B1 * (co2 - co2_ref)
    elif co2 <= co2_ref:
        alpha_p = D1
    else:
        alpha_p = D1 - B1**2 / (4 * A1)
    f_co2 = (alpha_p + C1 * np.sqrt(n2o)) * np.log(co2 / co2_ref)
    f_ch4 = (A3 * np.sqrt(ch4) + B3 * np.sqrt(n2o) + D3) * (np.sqrt(ch4) - np.sqrt(ch4_ref))
    f_n2o = (A2 * np.sqrt(co2) + B2 * np.sqrt(n2o) + C2 * np.sqrt(ch4) + D2) * (np.sqrt(n2o) - np.sqrt(n2o_ref))
    return f_co2, f_ch4, f_n2o


