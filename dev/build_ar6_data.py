"""Generate ``ipcc_ar6/data/ar6_parameters.json`` and ``ipcc_ar6/data/precursor_parameters.json``.

Every value follows the IPCC AR6 metric code (https://github.com/chrisroadmap/ar6, commit
24f279260fc2d1ebd09b2bd4114f2be11859e925, ``src/ar6/metrics`` and notebook
``335_chapter7_generate_metrics.ipynb``), which produced AR6 WG1 Table 7.SM.7. The radiative
efficiencies of CO2, CH4 and N2O are the Meinshausen et al. (2020) forcing for a +1 ppm / +1 ppb
perturbation at the notebook's 2019 background concentrations, times the AR6 tropospheric
adjustments, exactly as in that code. The formula is reimplemented here (identical to
``fair.forcing.ghg.meinshausen``), so the package needs no FaIR dependency.

    python dev/build_ar6_data.py           # write the files
    python dev/build_ar6_data.py --check   # exit 1 if a file is out of date

The precursor parameters (CO, VOC, H2, NOx) are published parameter sets, quoted below with
table and row; nothing is fitted. See ``precursor_parameters()``.
"""

